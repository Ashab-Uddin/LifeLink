(function initLanguageToggle() {
  const language = localStorage.getItem("lifelink_language") || "en";
  const translate = value => LIFE_LINK_TRANSLATIONS[language]?.[value] || value;

  function translatePage() {
    document.documentElement.lang = language === "bn" ? "bn" : "en";
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    textNodes.forEach(node => {
      if (node.parentElement.closest("script,style,template")) return;
      const trimmed = node.textContent.trim();
      if (!trimmed || !LIFE_LINK_TRANSLATIONS[language]?.[trimmed]) return;
      node.textContent = node.textContent.replace(trimmed, translate(trimmed));
    });
    document.querySelectorAll("[data-i18n]").forEach(element => {
      const key = element.dataset.i18n;
      element.textContent = translate(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
      element.placeholder = translate(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("input[placeholder]").forEach(element => {
      const translated = translate(element.placeholder);
      element.placeholder = translated;
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
      element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel));
    });
    const languageSwitch = document.getElementById("language-switch");
    if (languageSwitch) {
      languageSwitch.querySelector("[data-language=bn]").classList.toggle("active", language === "bn");
      languageSwitch.querySelector("[data-language=en]").classList.toggle("active", language === "en");
      languageSwitch.setAttribute("aria-label", language === "bn" ? "Switch to English" : "বাংলায় পরিবর্তন করুন");
    }
  }

  function addControls() {
    const navbar = document.querySelector(".navbar");
    const target = navbar || document.querySelector(".auth-page");
    if (!target || document.getElementById("language-switch")) return;

    const actions = document.createElement("div");
    actions.className = "navbar-actions";

    const languageSwitch = document.createElement("div");
    languageSwitch.id = "language-switch";
    languageSwitch.className = "language-switch";
    languageSwitch.setAttribute("role", "group");
    languageSwitch.innerHTML = `
      <button type="button" data-language="bn">BN</button>
      <button type="button" data-language="en">EN</button>`;

    languageSwitch.querySelectorAll("button").forEach(button => {
      button.addEventListener("click", () => {
        const nextLanguage = button.dataset.language;
        localStorage.setItem("lifelink_language", nextLanguage);
        window.location.reload();
      });
    });
    actions.appendChild(languageSwitch);

    if (navbar) {
      const authLinks = document.createElement("div");
      authLinks.className = "auth-links";
      authLinks.innerHTML = `
        <a class="auth-signup" href="/index/signup.html">Sign up</a>`;
      actions.appendChild(authLinks);

      const moreButton = document.createElement("button");
      moreButton.className = "navbar-more";
      moreButton.type = "button";
      moreButton.setAttribute("aria-label", "Open more options");
      moreButton.setAttribute("aria-expanded", "false");
      moreButton.innerHTML = "<span></span><span></span><span></span>";
      moreButton.addEventListener("click", () => {
        const isOpen = navbar.classList.toggle("utilities-open");
        moreButton.setAttribute("aria-expanded", String(isOpen));
      });
      navbar.appendChild(actions);
      navbar.appendChild(moreButton);
    } else {
      target.appendChild(actions);
    }
  }

  document.addEventListener("DOMContentLoaded", () => {
    addControls();
    translatePage();
  });

  window.lifeLinkTranslate = translatePage;
  window.lifeLinkText = translate;
  window.lifeLinkSymptomLabel = symptom => language === "bn"
    ? LIFE_LINK_SYMPTOMS_BN[symptom] || symptom.replaceAll("_", " ")
    : symptom.replaceAll("_", " ").replace(/\b\w/g, c => c.toUpperCase());
  window.lifeLinkHealthText = value => language === "bn"
    ? LIFE_LINK_HEALTH_BN[String(value)] || String(value)
    : String(value);
  window.lifeLinkLanguage = language;
})();
